-- Every phone signs in again: a token made before the move names an id that now belongs to someone
-- else. Refresh tokens are revoked here; access tokens made before this moment are refused by the
-- server (TokensValidAfter).
UPDATE td.sessions SET revoked_at = now() WHERE revoked_at IS NULL;

