-- 0043 reserved player ids (owner, 2026-11-11, as in MonoCity):
--   1      the owner: the primary admin, who is also a player (and stays a freelancer)
--   2-7    the six powers, one system account each (faction id + 1); nobody signs in as them
--   8-10   held for later
--   11+    everyone else. Moderators and other admins are ordinary accounts from 11 up.
-- Players already here are moved: the admin with the lowest id becomes 1, the rest become 11, 12, ...
-- in their old order. On an empty database only the six power accounts and the counter are set, and
-- id 1 is made when the owner first signs in (TD_PRIMARY_ADMIN_EMAIL).

-- Moving an id means every row that points at it must follow.
DO $$
DECLARE r record;
BEGIN
    FOR r IN
        SELECT c.conrelid::regclass AS tbl, c.conname, pg_get_constraintdef(c.oid) AS def
        FROM pg_constraint c
        WHERE c.contype = 'f' AND c.confrelid = 'td.players'::regclass AND c.confupdtype <> 'c'
    LOOP
        EXECUTE format('ALTER TABLE %s DROP CONSTRAINT %I', r.tbl, r.conname);
        EXECUTE format('ALTER TABLE %s ADD CONSTRAINT %I %s ON UPDATE CASCADE', r.tbl, r.conname, r.def);
    END LOOP;
END $$;

-- An identity column that is GENERATED ALWAYS can't be given a value; allow it for this migration.
ALTER TABLE td.players ALTER COLUMN id SET GENERATED BY DEFAULT;

CREATE TEMP TABLE player_renumber ON COMMIT DROP AS
WITH owner AS (
    SELECT min(id) AS id FROM td.players WHERE is_admin AND type = 'player'
), others AS (
    SELECT p.id, row_number() OVER (ORDER BY p.id) AS n
    FROM td.players p CROSS JOIN owner
    WHERE p.id IS DISTINCT FROM owner.id
)
SELECT owner.id AS old_id, 1::bigint AS new_id FROM owner WHERE owner.id IS NOT NULL
UNION ALL
SELECT others.id, 10 + others.n FROM others;

-- Out of the way first, so no new id meets an old one.
UPDATE td.players SET id = id + 1000000;
UPDATE td.players p SET id = m.new_id FROM player_renumber m WHERE p.id = m.old_id + 1000000;

-- The admin log names a player by id in text.
UPDATE td.admin_actions a SET target = m.new_id::text
FROM player_renumber m
WHERE a.target = m.old_id::text AND (a.action LIKE 'player.%' OR a.action LIKE 'sanction.%');

